//! Installation of the user-level `rascal` launcher command.

use std::{
    ffi::OsStr,
    fs, io,
    path::{Path, PathBuf},
};

use dirs::home_dir;

pub const BUNDLE_ID: &str = "im.sush.rascal";
const MARKER: &str = "# Generated by Rascal CLI installer";
const COMMAND_NAME: &str = "rascal";

#[derive(Debug)]
pub enum CliError {
    NotBundled,
    HomeNotFound,
    ForeignFile(PathBuf),
    Io(io::Error),
}

impl std::fmt::Display for CliError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            CliError::NotBundled => write!(formatter, "Rascal.appから起動してください"),
            CliError::HomeNotFound => write!(formatter, "ホームディレクトリが見つかりません"),
            CliError::ForeignFile(path) => write!(
                formatter,
                "{} はRascalが作成したファイルではないため上書きできません",
                path.display()
            ),
            CliError::Io(error) => write!(formatter, "{error}"),
        }
    }
}

impl From<io::Error> for CliError {
    fn from(value: io::Error) -> Self {
        CliError::Io(value)
    }
}

pub struct CliStatus {
    pub command_path: PathBuf,
    pub installed: bool,
    pub in_path: bool,
    pub app_bundle: Option<PathBuf>,
}

pub struct InstallResult {
    pub command_path: PathBuf,
    pub in_path: bool,
}

pub fn status() -> CliStatus {
    let Some(home) = home_dir() else {
        return CliStatus {
            command_path: PathBuf::from(COMMAND_NAME),
            installed: false,
            in_path: false,
            app_bundle: None,
        };
    };
    let command_path = command_path(&home);
    let installed = fs::read_to_string(&command_path)
        .map(|contents| is_ours(&contents))
        .unwrap_or(false);
    let bin_dir = command_path.parent().map(Path::to_path_buf);
    let in_path = bin_dir
        .as_deref()
        .is_some_and(|dir| path_contains_dir(dir, std::env::var_os("PATH").as_deref()));
    CliStatus {
        command_path,
        installed,
        in_path,
        app_bundle: app_bundle_path(),
    }
}

pub fn install() -> Result<InstallResult, CliError> {
    let app = app_bundle_path().ok_or(CliError::NotBundled)?;
    let home = home_dir().ok_or(CliError::HomeNotFound)?;
    install_into(&home, &app)
}

pub fn uninstall() -> Result<(), CliError> {
    let home = home_dir().ok_or(CliError::HomeNotFound)?;
    uninstall_into(&home)
}

pub fn app_bundle_path() -> Option<PathBuf> {
    let exe = std::env::current_exe().ok()?;
    exe.ancestors()
        .find(|path| path.extension().is_some_and(|extension| extension == "app"))
        .map(Path::to_path_buf)
}

pub fn command_path(home: &Path) -> PathBuf {
    home.join(".local").join("bin").join(COMMAND_NAME)
}

/// Directory where the CLI launcher queues repositories to open.
pub fn requests_dir() -> Option<PathBuf> {
    dirs::data_dir().map(|dir| dir.join("Rascal").join("requests"))
}

/// Read and consume queued CLI open requests.
pub fn take_open_requests() -> Vec<PathBuf> {
    requests_dir()
        .as_deref()
        .map(take_requests_from)
        .unwrap_or_default()
}

/// Update an existing Rascal launcher to the current wrapper format.
pub fn refresh_installed() -> Result<(), CliError> {
    let Some(app) = app_bundle_path() else {
        return Ok(());
    };
    let Some(home) = home_dir() else {
        return Ok(());
    };
    let path = command_path(&home);
    let Ok(existing) = fs::read_to_string(&path) else {
        return Ok(());
    };
    if !is_ours(&existing) {
        return Ok(());
    }
    let script = wrapper_script(&app);
    if existing == script {
        return Ok(());
    }
    write_launcher(&path, &script)
}

fn install_into(home: &Path, app: &Path) -> Result<InstallResult, CliError> {
    let path = command_path(home);
    let bin_dir = path.parent().expect("command path has parent");
    fs::create_dir_all(bin_dir)?;

    if path.exists() {
        match fs::read_to_string(&path) {
            Ok(existing) if is_ours(&existing) => {}
            _ => return Err(CliError::ForeignFile(path)),
        }
    }

    let script = wrapper_script(app);
    write_launcher(&path, &script)?;

    Ok(InstallResult {
        in_path: path_contains_dir(bin_dir, std::env::var_os("PATH").as_deref()),
        command_path: path,
    })
}

fn write_launcher(path: &Path, script: &str) -> Result<(), CliError> {
    let bin_dir = path.parent().expect("command path has parent");
    fs::create_dir_all(bin_dir)?;
    let temporary = bin_dir.join(format!(".rascal-cli-{}.tmp", std::process::id()));
    let result = (|| -> Result<(), CliError> {
        fs::write(&temporary, script.as_bytes())?;
        set_executable(&temporary)?;
        fs::rename(&temporary, path)?;
        Ok(())
    })();
    if result.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    result
}

fn take_requests_from(dir: &Path) -> Vec<PathBuf> {
    let Ok(entries) = fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut requests: Vec<PathBuf> = entries
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.path())
        .filter(|path| {
            path.extension()
                .is_some_and(|extension| extension == "request")
        })
        .collect();
    requests.sort();

    let mut paths = Vec::new();
    for request in requests {
        let Ok(bytes) = fs::read(&request) else {
            continue;
        };
        let _ = fs::remove_file(&request);
        for path in bytes
            .split(|byte| *byte == 0)
            .filter(|path| !path.is_empty())
        {
            paths.push(path_from_bytes(path));
        }
    }
    paths
}

#[cfg(unix)]
fn path_from_bytes(bytes: &[u8]) -> PathBuf {
    use std::os::unix::ffi::OsStringExt;
    PathBuf::from(std::ffi::OsString::from_vec(bytes.to_vec()))
}

#[cfg(not(unix))]
fn path_from_bytes(bytes: &[u8]) -> PathBuf {
    PathBuf::from(String::from_utf8_lossy(bytes).into_owned())
}

fn uninstall_into(home: &Path) -> Result<(), CliError> {
    let path = command_path(home);
    match fs::read_to_string(&path) {
        Ok(contents) if is_ours(&contents) => {
            fs::remove_file(path)?;
            Ok(())
        }
        Ok(_) => Err(CliError::ForeignFile(path)),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error.into()),
    }
}

fn wrapper_script(app: &Path) -> String {
    let app = shell_quote(app.as_os_str());
    format!(
        r#"#!/bin/sh
{MARKER}
APP={app}
REQUESTS="$HOME/Library/Application Support/Rascal/requests"

open_app() {{
  if [ -d "$APP" ]; then
    exec /usr/bin/open -a "$APP"
  fi
  exec /usr/bin/open -b {BUNDLE_ID}
}}

if [ "$#" -eq 0 ]; then
  open_app
fi

umask 077
if ! /bin/mkdir -p "$REQUESTS"; then
  if [ -d "$APP" ]; then
    exec /usr/bin/open -a "$APP" --args "$@"
  fi
  exec /usr/bin/open -b {BUNDLE_ID} --args "$@"
fi

STAMP="$(/bin/date +%s)-$$"
TEMP="$REQUESTS/.pending-$STAMP"
if ! : > "$TEMP"; then
  exit 1
fi

for arg in "$@"; do
  if [ -d "$arg" ]; then
    abs="$(cd "$arg" 2>/dev/null && pwd -P)" || abs="$arg"
  else
    case "$arg" in
      /*) abs="$arg" ;;
      *) abs="$(pwd -P)/$arg" ;;
    esac
  fi
  if ! printf '%s\0' "$abs" >> "$TEMP"; then
    /bin/rm -f "$TEMP"
    exit 1
  fi
done

if ! /bin/mv "$TEMP" "$REQUESTS/$STAMP.request"; then
  /bin/rm -f "$TEMP"
  exit 1
fi

open_app
"#
    )
}

fn is_ours(contents: &str) -> bool {
    contents.lines().take(3).any(|line| line == MARKER)
}

fn shell_quote(value: &OsStr) -> String {
    let value = value.to_string_lossy();
    format!("'{}'", value.replace('\'', "'\\''"))
}

fn path_contains_dir(dir: &Path, path: Option<&OsStr>) -> bool {
    let Some(path) = path else {
        return false;
    };
    std::env::split_paths(path).any(|entry| entry == dir)
}

#[cfg(unix)]
fn set_executable(path: &Path) -> io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    let mut permissions = fs::metadata(path)?.permissions();
    permissions.set_mode(0o755);
    fs::set_permissions(path, permissions)
}

#[cfg(not(unix))]
fn set_executable(_path: &Path) -> io::Result<()> {
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::ffi::OsString;

    use super::*;

    #[test]
    fn quotes_shell_paths() {
        assert_eq!(
            shell_quote(OsStr::new("/tmp/Rascal.app")),
            "'/tmp/Rascal.app'"
        );
        assert_eq!(
            shell_quote(OsStr::new("/tmp/it's Rascal.app")),
            "'/tmp/it'\\''s Rascal.app'"
        );
    }

    #[test]
    fn wrapper_contains_marker_and_paths() {
        let script = wrapper_script(Path::new("/Applications/Rascal.app"));
        assert!(script.contains(MARKER));
        assert!(script.contains("'/Applications/Rascal.app'"));
        assert!(script.contains(BUNDLE_ID));
        assert!(script.contains("Rascal/requests"));
        assert!(!script.contains("--args /tmp"));
        assert!(script.contains("printf '%s\\0'"));
    }

    #[test]
    fn installs_and_uninstalls() {
        let home = tempfile::tempdir().unwrap();
        let app = home.path().join("Rascal.app");
        let path = command_path(home.path());
        assert!(!path.exists());

        let result = install_into(home.path(), &app).unwrap();
        assert_eq!(result.command_path, path);
        assert!(path.exists());
        assert!(is_ours(&fs::read_to_string(&path).unwrap()));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            assert_eq!(
                fs::metadata(&path).unwrap().permissions().mode() & 0o777,
                0o755
            );
        }

        install_into(home.path(), &app).unwrap();
        uninstall_into(home.path()).unwrap();
        assert!(!path.exists());
        uninstall_into(home.path()).unwrap();
    }

    #[test]
    fn refuses_foreign_command() {
        let home = tempfile::tempdir().unwrap();
        let path = command_path(home.path());
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, "#!/bin/sh\necho other\n").unwrap();
        let error = install_into(home.path(), Path::new("/Applications/Rascal.app"));
        assert!(matches!(error, Err(CliError::ForeignFile(_))));
        assert_eq!(
            fs::read_to_string(&path).unwrap(),
            "#!/bin/sh\necho other\n"
        );
    }

    #[test]
    fn detects_path_entries() {
        let dir = Path::new("/Users/example/.local/bin");
        let path = OsString::from("/usr/bin:/Users/example/.local/bin:/bin");
        assert!(path_contains_dir(dir, Some(&path)));
        let path = OsString::from("/usr/bin:/bin");
        assert!(!path_contains_dir(dir, Some(&path)));
        assert!(!path_contains_dir(dir, None));
    }

    #[test]
    fn takes_and_removes_open_requests() {
        let dir = tempfile::tempdir().unwrap();
        fs::write(dir.path().join("02.request"), b"/second").unwrap();
        fs::write(dir.path().join("01.request"), b"/first\0/with space\0").unwrap();
        fs::write(dir.path().join(".pending-123"), b"/ignored").unwrap();

        let paths = take_requests_from(dir.path());
        assert_eq!(
            paths,
            vec![
                PathBuf::from("/first"),
                PathBuf::from("/with space"),
                PathBuf::from("/second")
            ]
        );
        assert!(!dir.path().join("01.request").exists());
        assert!(!dir.path().join("02.request").exists());
        assert!(dir.path().join(".pending-123").exists());
        assert!(take_requests_from(dir.path()).is_empty());
    }

    #[test]
    fn updates_wrapper_for_new_app_location() {
        let first = wrapper_script(Path::new("/Applications/Rascal.app"));
        let second = wrapper_script(Path::new("/Users/me/Rascal.app"));
        assert_ne!(first, second);
        assert!(second.contains("/Users/me/Rascal.app"));
    }
}
